// Isolated browser + native-worker regression; never changes a live project.
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createFrameLineServer } from '../server/index.ts';
import { run } from '../server/media.ts';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
delete process.env.FRAME_LINE_SIGNUP_CODE;
const directory=await mkdtemp(join(tmpdir(),'frameline-flow-browser-'));
const app=createFrameLineServer({dataDir:directory,distDir:resolve('dist')});
await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
const url=`http://127.0.0.1:${app.server.address().port}`;
const browser=await chromium.launch({headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1512,height:982}}),page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>{window.flowVideos=[];const create=document.createElement.bind(document);document.createElement=(name,...args)=>{const element=create(name,...args);if(name==='video')window.flowVideos.push(element);return element;};});
const state=async()=>await(await context.request.get(url+'/api/state')).json();
try {
  const input=join(directory,'Motion.mp4');
  await run('ffmpeg',['-v','error','-f','lavfi','-i','testsrc2=size=640x360:rate=24:duration=12','-c:v','libx264','-pix_fmt','yuv420p',input]);
  await page.goto(url);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByRole('textbox',{name:'Your name'}).fill('Flow QA');
  await page.getByRole('textbox',{name:'Email address'}).fill('flow@example.test');
  await page.locator('input[type=password]').fill('Optical-flow-check-2026');
  await page.getByRole('button',{name:'Create account',exact:true}).last().click();
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByRole('textbox',{name:'Project name'}).fill('Optical flow check');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByLabel('Upload media files').setInputFiles(input);
  await page.waitForFunction(()=>document.querySelector('.media-state-icon.ready'),{},{timeout:60000});
  await page.getByRole('button',{name:'Add Motion.mp4 to timeline',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.save-status')?.textContent==='Saved');
  const saved=await state(),clip=saved.state.clips[0];
  clip.duration=6;clip.properties.speed=100;saved.state.timelines.find(t=>t.id===clip.timelineId).duration=6;
  clip.keyframes={'properties.speed':[{id:'a',time:0,value:100,interpolation:'bezier',curve:[.3,0,.7,1]},{id:'b',time:2,value:50,interpolation:'linear'},{id:'c',time:4,value:50,interpolation:'bezier',curve:[.5,0,.8,1]},{id:'d',time:5,value:500,interpolation:'linear'}]};
  const write=await context.request.put(url+'/api/state',{data:saved});assert.equal(write.status(),200,await write.text());
  await page.reload();
  await page.locator('.timeline-clip').first().click();
  await page.getByRole('checkbox',{name:'Optical flow',exact:true}).check({timeout:30000});
  await page.waitForFunction(()=>window.flowVideos.some(v=>v.src.includes('/api/optical-flow/')&&v.readyState>=2),{},{timeout:60000});
  const previewUrl=await page.evaluate(()=>window.flowVideos.find(v=>v.src.includes('/api/optical-flow/')&&v.readyState>=2).src);
  const anonymous=await browser.newContext();assert.equal((await anonymous.request.get(previewUrl)).status(),401);await anonymous.close();
  const range=await context.request.get(previewUrl,{headers:{Range:'bytes=0-99'}});assert.equal(range.status(),206);assert.equal((await range.body()).length,100);
  console.log('PASS native optical-flow preparation and authenticated browser decode');
  await page.getByRole('slider',{name:'Timeline zoom',exact:true}).evaluate(el=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'5');el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.getByRole('button',{name:`Expand keyframes for ${saved.state.tracks.find(t=>t.id===clip.trackId).name}`}).first().click();
  await page.getByRole('button',{name:'Expand Speed curve',exact:true}).click();
  await page.getByRole('button',{name:'Focus Speed ramp 100% to 50%',exact:true}).click();
  const first=await page.locator('svg[aria-label="Speed graph editor"] .graph-axis').allTextContents();
  await page.getByRole('button',{name:'Focus Speed ramp 50% to 500%',exact:true}).click();
  const last=await page.locator('svg[aria-label="Speed graph editor"] .graph-axis').allTextContents();
  assert.notDeepEqual(first,last);
  await page.getByRole('button',{name:'Focus Speed ramp 100% to 50%',exact:true}).click();
  await mkdir(resolve('artifacts/optical-flow'),{recursive:true});
  await page.locator('svg[aria-label="Speed graph editor"]').scrollIntoViewIfNeeded();
  await page.screenshot({path:resolve('artifacts/optical-flow/editor.png')});
  await page.getByRole('button',{name:'Play playback',exact:true}).click();
  await page.waitForTimeout(4700);
  const playing=await page.evaluate(()=>window.flowVideos.filter(v=>v.src.includes('/api/optical-flow/')&&!v.paused).map(v=>({time:v.currentTime,rate:v.playbackRate,frames:v.getVideoPlaybackQuality().totalVideoFrames,dropped:v.getVideoPlaybackQuality().droppedVideoFrames})));
  assert.ok(playing.some(v=>v.time>.5&&v.rate===1),JSON.stringify(playing));
  await page.getByRole('button',{name:'Pause playback',exact:true}).click();
  const enabled=(await state()).state.clips.find(c=>c.id===clip.id);assert.equal(enabled.properties.opticalFlow,true);
  console.log('PASS independent ramp scales and cached playback',JSON.stringify({first,last,playing}));
  assert.deepEqual(errors,[]);
} catch(error) {await page.screenshot({path:resolve('artifacts/optical-flow/browser-failure.png')});throw error;} finally {await browser.close();await app.close();await rm(directory,{recursive:true,force:true});}
