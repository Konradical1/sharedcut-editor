"""Generate the browser transform from pinned OpenColorIO, never hand-edit its math."""
import json
from pathlib import Path
import PyOpenColorIO as ocio
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
if ocio.__version__!='2.5.2': raise RuntimeError('This reference pipeline requires OpenColorIO 2.5.2; run npm run setup:color.')
CONFIG='studio-config-v4.0.0_aces-v2.0_ocio-v2.5'
VIEW='ACES 2.0 - SDR 100 nits (Rec.709)'
config=ocio.Config.CreateFromBuiltinConfig(CONFIG)
processor=config.getProcessor('Linear Rec.709 (sRGB)','Rec.1886 Rec.709 - Display',VIEW,ocio.TRANSFORM_DIR_FORWARD)
desc=ocio.GpuShaderDesc.CreateShaderDesc()
desc.setLanguage(ocio.GPU_LANGUAGE_GLSL_ES_3_0)
desc.setAllowTexture1D(False)
desc.setFunctionName('ocio_aces2')
desc.setResourcePrefix('aces2_')
processor.getDefaultGPUProcessor().extractGpuShaderInfo(desc)
assert not list(desc.get3DTextures()) and not list(desc.getUniforms())
textures=[{'sampler':t.samplerName,'width':t.width,'height':t.height,'channels':1 if str(t.channel)=='TextureType.TEXTURE_RED_CHANNEL' else 3,'values':t.getValues().flatten().tolist()} for t in desc.getTextures()]
text='// Generated by scripts/generate-aces.py with OpenColorIO '+ocio.__version__+'.\n// '+CONFIG+'; '+VIEW+'. See docs/color-reference.md for provenance.\n'
text+='export const acesShader = '+json.dumps(desc.getShaderText())+';\n'
spaces={'Rec.709':'Linear Rec.709 (sRGB)','Rec.2020':'Linear Rec.2020','DaVinci Wide Gamut':'Linear DaVinci WideGamut','S-Gamut3':'S-Log3 S-Gamut3','S-Gamut3.Cine':'S-Log3 S-Gamut3.Cine'}
matrices={}
for gamut,space in spaces.items():
    matrix=np.eye(4)
    for transform in config.getProcessor(space,'ACES2065-1').createGroupTransform():
        assert isinstance(transform,(ocio.MatrixTransform,ocio.LogCameraTransform))
        if isinstance(transform,ocio.MatrixTransform):
            assert not any(transform.getOffset())
            matrix=np.array(transform.getMatrix()).reshape(4,4)@matrix
    matrices[gamut]=matrix[:3,:3].tolist()
text+='export const acesMatrices:Record<string,number[][]> = '+json.dumps(matrices,separators=(',',':'))+';\n'
text+='export const acesTextures = '+json.dumps(textures,separators=(',',':'))+';\n'
(ROOT/'src/services/aces.generated.ts').write_text(text)
print('Generated ACES 2 shader and',len(textures),'float tables')
