import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { chromium } from 'playwright';
import { createFrameLineServer } from '../server/index.ts';
delete process.env.FRAME_LINE_SIGNUP_CODE;
const dir = await mkdtemp(join(tmpdir(), 'sharedcut-activity-browser-'));
const app = createFrameLineServer({ dataDir: dir, distDir: resolve('dist') });
await new Promise(r => app.server.listen(0, '127.0.0.1', r));
const url = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  const signup = await context.request.post(`${url}/api/auth/signup`, { data: { name: 'Activity Editor', email: 'activity@browser.test', password: 'activity browser test password' } });
  assert.equal(signup.status(), 201); const { user } = await signup.json();
  const saved = await (await context.request.get(`${url}/api/state`)).json();
  saved.state.projects.push({ id: 'activity-film', name: 'Activity film', description: '', shared: false, thumbnail: '', modifiedAt: Date.now(), duration: 0, resolution: '1920 × 1080', fps: 24, status: 'In progress', members: [{ userId: user.id, role: 'Owner' }] });
  assert.equal((await context.request.put(`${url}/api/state`, { data: saved })).status(), 200);
  const db = new DatabaseSync(join(dir, 'frameline.sqlite'));
  const set = (kind, age) => db.prepare('UPDATE project_activity SET kind=?,timestamp=? WHERE projectId=?').run(kind, Date.now() - age, 'activity-film');
  set('edited', 32 * 60_000);
  await page.goto(url);
  await page.getByRole('button', { name: /Open Activity film/ }).waitFor();
  assert.equal(await page.locator('.drive-project-activity').first().innerText(), 'Activity Editor edited this 32 minutes ago');
  const out = resolve('artifacts/qa/activity'); await mkdir(out, { recursive: true });
  await page.screenshot({ path: join(out, 'grid.png') });
  await page.getByRole('button', { name: 'List view', exact: true }).click();
  assert.ok(await page.locator('.drive-project-activity').first().isVisible());
  await page.screenshot({ path: join(out, 'list.png') });
  set('viewed', 2 * 3600_000); await page.reload();
  await page.getByText('Activity Editor viewed this 2 hours ago', { exact: true }).first().waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(out, 'phone.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  set('viewed', 86_400_000); await page.reload();
  await page.getByRole('button', { name: /Open Activity film/ }).waitFor();
  assert.equal(await page.locator('.drive-project-activity').first().innerText(), '');
  assert.deepEqual(errors, []); db.close();
  console.log('PASS activity labels in grid, list and phone layouts; 24-hour expiry; no browser errors');
} finally { await context.close(); await browser.close(); await app.close(); await rm(dir, { recursive: true, force: true }); }
